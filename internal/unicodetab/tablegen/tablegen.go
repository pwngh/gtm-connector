// Package tablegen writes tables.go for unicodetab from testdata/oracle/unicode, so every Unicode property an
// evidence rule uses comes from what CPython 3.14.6 recorded there, and never from Go's unicode package or
// RE2. It reads no Python: go generate runs it on the committed data.
package tablegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
)

// Generate returns the source of tables.go from the oracle folder.
func Generate(oracle string) (source []byte, err error) {
	// The readers below stop at the first problem by panicking with a failure, which ends here.
	defer func() {
		if r := recover(); r != nil {
			f, ok := r.(failure)
			if !ok {
				panic(r)
			}
			source, err = nil, f
		}
	}()
	var manifest struct {
		Python  string `json:"python_version"`
		Unicode string `json:"unicode_version"`
	}
	read(filepath.Join(oracle, "manifest.json"), &manifest)
	if manifest.Unicode != "16.0.0" {
		fail("the oracle records Unicode %s; the tables are for 16.0.0", manifest.Unicode)
	}

	var categories struct {
		Runs [][3]any `json:"runs"`
	}
	read(filepath.Join(oracle, "unicode", "categories.json"), &categories)
	var predicates map[string]json.RawMessage
	read(filepath.Join(oracle, "unicode", "predicates.json"), &predicates)
	var regex struct {
		Classes    map[string][][2]int `json:"classes"`
		IgnoreCase map[string][][2]int `json:"ignorecase"`
	}
	read(filepath.Join(oracle, "unicode", "regex_classes.json"), &regex)
	var cases struct {
		Lower      [][2]json.RawMessage `json:"lower"`
		FinalSigma map[string][][2]int  `json:"final_sigma"`
	}
	read(filepath.Join(oracle, "unicode", "case.json"), &cases)
	var nfc struct {
		Combining    [][3]int             `json:"combining_class"`
		NFD          [][2]json.RawMessage `json:"nfd"`
		Compositions [][3]int             `json:"compositions"`
	}
	read(filepath.Join(oracle, "unicode", "nfc.json"), &nfc)
	var netloc struct {
		Ranges [][2]int `json:"ranges"`
	}
	read(filepath.Join(oracle, "unicode", "nfkc_netloc.json"), &netloc)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen/main.go from testdata/oracle/unicode; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package unicodetab\n\n")
	fmt.Fprintf(&b, "// UnicodeVersion is the Unicode version of the oracle, CPython %s.\n", manifest.Python)
	fmt.Fprintf(&b, "const UnicodeVersion = %q\n\n", manifest.Unicode)

	// Categories as runs, with the names in order of first use.
	var names []string
	index := map[string]int{}
	fmt.Fprintf(&b, "var categoryRuns = []categoryRun{\n")
	for _, run := range categories.Runs {
		name := run[2].(string)
		if _, ok := index[name]; !ok {
			index[name] = len(names)
			names = append(names, name)
		}
		fmt.Fprintf(&b, "{0x%x, 0x%x, %d},\n", int(run[0].(float64)), int(run[1].(float64)), index[name])
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "var categoryNames = %#v\n\n", names)

	for _, name := range []string{"isspace", "isdigit", "isdecimal", "isprintable", "islower", "isupper",
		"istitle_only", "isalpha"} {
		var ranges [][2]int
		if err := json.Unmarshal(predicates[name], &ranges); err != nil {
			fail("predicates.json %s: %v", name, err)
		}
		writeRanges(&b, "py_"+name, ranges)
	}
	writeRanges(&b, "re_space", regex.Classes[`\s`])
	writeRanges(&b, "re_digit", regex.Classes[`\d`])
	writeRanges(&b, "re_word", regex.Classes[`\w`])
	writeRanges(&b, "ic_az", regex.IgnoreCase["[a-z]"])
	fmt.Fprintf(&b, "var icLetterRanges = [26][]rng{\n")
	for letter := 'a'; letter <= 'z'; letter++ {
		fmt.Fprintf(&b, "%s,\n", rangesLiteral(regex.IgnoreCase[string(letter)]))
	}
	fmt.Fprintf(&b, "}\n\n")
	writeRanges(&b, "case_ignorable", cases.FinalSigma["case_ignorable"])
	writeRanges(&b, "cased", cases.FinalSigma["cased"])
	writeRanges(&b, "nfkc_netloc", netloc.Ranges)

	fmt.Fprintf(&b, "var lowerEntries = []mapping{\n")
	for _, entry := range cases.Lower {
		writeMapping(&b, entry)
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "var combiningRuns = []combiningRun{\n")
	for _, run := range nfc.Combining {
		fmt.Fprintf(&b, "{0x%x, 0x%x, %d},\n", run[0], run[1], run[2])
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "var decompositionEntries = []mapping{\n")
	for _, entry := range nfc.NFD {
		writeMapping(&b, entry)
	}
	fmt.Fprintf(&b, "}\n\n")
	sort.Slice(nfc.Compositions, func(i, j int) bool {
		a, c := nfc.Compositions[i], nfc.Compositions[j]
		return a[0] < c[0] || a[0] == c[0] && a[1] < c[1]
	})
	fmt.Fprintf(&b, "var compositionEntries = [][3]rune{\n")
	for _, pair := range nfc.Compositions {
		fmt.Fprintf(&b, "{0x%x, 0x%x, 0x%x},\n", pair[0], pair[1], pair[2])
	}
	fmt.Fprintf(&b, "}\n")

	return format.Source(b.Bytes())
}

type failure struct{ error }

func fail(message string, args ...any) { panic(failure{fmt.Errorf(message, args...)}) }

func read(path string, into any) {
	data, err := os.ReadFile(path)
	if err != nil {
		fail("%w", err)
	}
	if err := json.Unmarshal(data, into); err != nil {
		fail("%s: %v", path, err)
	}
}

func rangesLiteral(ranges [][2]int) string {
	var b bytes.Buffer
	b.WriteString("{")
	for i, r := range ranges {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "{0x%x, 0x%x}", r[0], r[1])
	}
	b.WriteString("}")
	return b.String()
}

func writeRanges(b *bytes.Buffer, name string, ranges [][2]int) {
	fmt.Fprintf(b, "var %sRanges = []rng{\n", camel(name))
	for i, r := range ranges {
		fmt.Fprintf(b, "{0x%x, 0x%x},", r[0], r[1])
		if i%6 == 5 {
			b.WriteString("\n")
		}
	}
	fmt.Fprintf(b, "\n}\n\n")
}

func writeMapping(b *bytes.Buffer, entry [2]json.RawMessage) {
	var code int
	var parts []int
	if err := json.Unmarshal(entry[0], &code); err != nil {
		fail("%w", err)
	}
	if err := json.Unmarshal(entry[1], &parts); err != nil {
		fail("%w", err)
	}
	fmt.Fprintf(b, "{0x%x, []rune{", code)
	for i, part := range parts {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "0x%x", part)
	}
	b.WriteString("}},\n")
}

func camel(name string) string {
	var b bytes.Buffer
	upper := false
	for i, c := range name {
		switch {
		case c == '_':
			upper = true
		case upper && i > 0:
			b.WriteRune(c - 'a' + 'A')
			upper = false
		default:
			b.WriteRune(c)
		}
	}
	return b.String()
}
